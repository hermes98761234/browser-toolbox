// Generates an original IFC4 sample: a small two-storey house (millimetre units).
// It deliberately exercises many representation types: rectangle / hollow / circle / I-shape /
// arbitrary (+voids, polyline and indexed curves) extrusions, faceted B-rep, polygonal and
// triangulated face sets, mapped items (window type), styled items, property sets and quantities,
// plus one revolved solid that the viewer reports as unsupported.

export function sampleIfc(): string {
  const L: string[] = []
  let n = 0
  const e = (type: string, ...args: (string | number)[]) => {
    n++
    L.push(`#${n}=${type}(${args.join(',')});`)
    return `#${n}`
  }
  const s = (x: string) => `'${x.replace(/'/g, "''")}'`
  const f = (x: number) => (Number.isInteger(x) ? `${x}.` : String(x))
  const list = (xs: (string | number)[]) => `(${xs.join(',')})`
  const ABC = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz_$'
  let seed = 20261018
  const guid = () => {
    let g = ABC[seed % 4]
    for (let i = 1; i < 22; i++) {
      seed = (Math.imul(seed, 1103515245) + 12345) >>> 0
      g += ABC[(seed >>> 10) % 64]
    }
    return s(g)
  }
  const pt = (...c: number[]) => e('IFCCARTESIANPOINT', list(c.map(f)))
  const dir = (...c: number[]) => e('IFCDIRECTION', list(c.map(f)))
  const ax3 = (x = 0, y = 0, z = 0, axis?: string, ref?: string) => e('IFCAXIS2PLACEMENT3D', pt(x, y, z), axis ?? '$', ref ?? '$')
  const ax2 = (x = 0, y = 0) => e('IFCAXIS2PLACEMENT2D', pt(x, y), '$')
  const place = (rel: string | null, x: number, y: number, z: number, ref?: string) => e('IFCLOCALPLACEMENT', rel ?? '$', ax3(x, y, z, ref ? Z : undefined, ref))

  // ---- context, units, project
  const Z = dir(0, 0, 1)
  const X = dir(1, 0, 0)
  const Yd = dir(0, 1, 0)
  const ctx = e('IFCGEOMETRICREPRESENTATIONCONTEXT', '$', s('Model'), 3, '1.E-05', ax3(), '$')
  const body = e('IFCGEOMETRICREPRESENTATIONSUBCONTEXT', s('Body'), s('Model'), '*', '*', '*', '*', ctx, '$', '.MODEL_VIEW.', '$')
  const units = e('IFCUNITASSIGNMENT', list([
    e('IFCSIUNIT', '*', '.LENGTHUNIT.', '.MILLI.', '.METRE.'), e('IFCSIUNIT', '*', '.AREAUNIT.', '$', '.SQUARE_METRE.'),
    e('IFCSIUNIT', '*', '.VOLUMEUNIT.', '$', '.CUBIC_METRE.'), e('IFCSIUNIT', '*', '.PLANEANGLEUNIT.', '$', '.RADIAN.'),
  ]))
  const project = e('IFCPROJECT', guid(), '$', s('Sample house'), s('Two-storey demo house generated by Browser Toolbox'), '$', '$', '$', list([ctx]), units)

  // ---- styles
  const style = (name: string, r: number, g: number, b: number, tr = 0) =>
    e('IFCSURFACESTYLE', s(name), '.BOTH.', list([e('IFCSURFACESTYLESHADING', e('IFCCOLOURRGB', '$', f(r), f(g), f(b)), f(tr))]))
  const ST = {
    wall: style('Render', 0.93, 0.89, 0.8), roof: style('Roof tiles', 0.66, 0.24, 0.17), glass: style('Glass', 0.55, 0.75, 0.92, 0.6),
    frame: style('Frame', 0.97, 0.97, 0.97), door: style('Oak', 0.48, 0.32, 0.18), slab: style('Concrete', 0.7, 0.7, 0.68),
    steel: style('Steel', 0.42, 0.47, 0.53), brick: style('Brick', 0.62, 0.3, 0.24), wood: style('Pine', 0.78, 0.62, 0.4),
    space: style('Space', 0.4, 0.7, 1, 0.82), porcelain: style('Porcelain', 0.95, 0.95, 0.97),
  }
  const styled = (item: string, st: string) => {
    e('IFCSTYLEDITEM', item, list([st]), '$')
    return item
  }

  // ---- geometry helpers
  const shape = (items: string[], kind = 'SweptSolid') => e('IFCPRODUCTDEFINITIONSHAPE', '$', '$', list([e('IFCSHAPEREPRESENTATION', body, s('Body'), s(kind), list(items))]))
  const rectProf = (w: number, h: number, cx = 0, cy = 0) => e('IFCRECTANGLEPROFILEDEF', '.AREA.', '$', ax2(cx, cy), f(w), f(h))
  const extrude = (prof: string, depth: number, pos = ax3(), d = Z) => e('IFCEXTRUDEDAREASOLID', prof, pos, d, f(depth))
  const polyline = (pts: [number, number][]) => e('IFCPOLYLINE', list([...pts, pts[0]].map(([x, y]) => pt(x, y))))

  // ---- spatial structure
  const sitePl = place(null, 0, 0, 0)
  const site = e('IFCSITE', guid(), '$', s('Plot 7'), '$', '$', sitePl, '$', '$', '.ELEMENT.', '$', '$', '$', '$', '$')
  const bldPl = place(sitePl, 0, 0, 0)
  const bld = e('IFCBUILDING', guid(), '$', s('Sample house'), '$', '$', bldPl, '$', s('Detached house'), '.ELEMENT.', '$', '$', '$')
  const st0Pl = place(bldPl, 0, 0, 0)
  const st1Pl = place(bldPl, 0, 0, 3000)
  const st0 = e('IFCBUILDINGSTOREY', guid(), '$', s('Ground floor'), '$', '$', st0Pl, '$', s('Level 0'), '.ELEMENT.', f(0))
  const st1 = e('IFCBUILDINGSTOREY', guid(), '$', s('First floor'), '$', '$', st1Pl, '$', s('Level 1'), '.ELEMENT.', f(3000))
  e('IFCRELAGGREGATES', guid(), '$', '$', '$', project, list([site]))
  e('IFCRELAGGREGATES', guid(), '$', '$', '$', site, list([bld]))
  e('IFCRELAGGREGATES', guid(), '$', '$', '$', bld, list([st0, st1]))

  const contained: Record<string, string[]> = { [st0]: [], [st1]: [] }
  const T = 250, W = 10000, D = 8000, H = 2800

  // ---- properties
  const single = (name: string, v: string) => e('IFCPROPERTYSINGLEVALUE', s(name), '$', v, '$')
  const pset = (objs: string[], name: string, props: string[]) => e('IFCRELDEFINESBYPROPERTIES', guid(), '$', '$', '$', list(objs), e('IFCPROPERTYSET', guid(), '$', s(name), '$', list(props)))
  const qto = (objs: string[], name: string, qs: string[]) => e('IFCRELDEFINESBYPROPERTIES', guid(), '$', '$', '$', list(objs), e('IFCELEMENTQUANTITY', guid(), '$', s(name), '$', '$', list(qs)))
  const qLen = (name: string, v: number) => e('IFCQUANTITYLENGTH', s(name), '$', '$', f(v), '$')
  const qArea = (name: string, v: number) => e('IFCQUANTITYAREA', s(name), '$', '$', f(v), '$')
  const qVol = (name: string, v: number) => e('IFCQUANTITYVOLUME', s(name), '$', '$', f(v), '$')

  // ---- walls (rectangle extrusions placed along their axis)
  const wall = (storey: string, stPl: string, name: string, x: number, y: number, len: number, alongY: boolean, ext = true) => {
    const pl = place(stPl, x, y, 0, alongY ? Yd : X)
    const solid = styled(extrude(rectProf(len, T, len / 2, 0), H), ST.wall)
    const w = e('IFCWALL', guid(), '$', s(name), '$', s(ext ? 'Exterior wall 250' : 'Partition'), pl, shape([solid]), '$', '.STANDARD.')
    contained[storey].push(w)
    pset([w], 'Pset_WallCommon', [single('IsExternal', `IFCBOOLEAN(${ext ? '.T.' : '.F.'})`), single('LoadBearing', 'IFCBOOLEAN(.T.)'), single('FireRating', "IFCLABEL('REI 60')"), single('ThermalTransmittance', 'IFCTHERMALTRANSMITTANCEMEASURE(0.24)')])
    qto([w], 'Qto_WallBaseQuantities', [qLen('Length', len), qLen('Height', H), qLen('Width', T), qVol('GrossVolume', (len * H * T) / 1e9)])
    return { w, pl }
  }
  const sides = (storey: string, stPl: string, lvl: string) => ({
    S: wall(storey, stPl, `${lvl} south wall`, 0, T / 2, W, false),
    N: wall(storey, stPl, `${lvl} north wall`, 0, D - T / 2, W, false),
    Wt: wall(storey, stPl, `${lvl} west wall`, T / 2, T, D - 2 * T, true),
    E: wall(storey, stPl, `${lvl} east wall`, W - T / 2, T, D - 2 * T, true),
  })
  const g = sides(st0, st0Pl, 'GF')
  const u = sides(st1, st1Pl, '1F')

  // Interior L-shaped partition: arbitrary closed profile from an indexed poly curve (IFC4).
  {
    const pts: [number, number][] = [[5000, T], [5120, T], [5120, 4500], [W - T, 4500], [W - T, 4620], [5000, 4620]]
    const curve = e('IFCINDEXEDPOLYCURVE', e('IFCCARTESIANPOINTLIST2D', list(pts.map(([x, y]) => list([f(x), f(y)])))), '$', '.F.')
    const prof = e('IFCARBITRARYCLOSEDPROFILEDEF', '.AREA.', s('Partition outline'), curve)
    const solid = styled(extrude(prof, H), ST.wall)
    const w = e('IFCWALL', guid(), '$', s('GF kitchen partition'), '$', s('Partition 120'), place(st0Pl, 0, 0, 0), shape([solid]), '$', '.PARTITIONING.')
    contained[st0].push(w)
    pset([w], 'Pset_WallCommon', [single('IsExternal', 'IFCBOOLEAN(.F.)'), single('LoadBearing', 'IFCBOOLEAN(.F.)'), single('AcousticRating', "IFCLABEL('Rw 42 dB')")])
  }

  // ---- slabs: ground slab (rectangle), first floor with a stair void
  {
    const solid = styled(extrude(rectProf(W, D, W / 2, D / 2), 200, ax3(0, 0, -200)), ST.slab)
    const sl = e('IFCSLAB', guid(), '$', s('Ground slab'), '$', '$', place(st0Pl, 0, 0, 0), shape([solid]), '$', '.BASESLAB.')
    contained[st0].push(sl)
    pset([sl], 'Pset_SlabCommon', [single('IsExternal', 'IFCBOOLEAN(.F.)'), single('LoadBearing', 'IFCBOOLEAN(.T.)')])
    qto([sl], 'Qto_SlabBaseQuantities', [qLen('Depth', 200), qArea('GrossArea', (W * D) / 1e6), qVol('GrossVolume', (W * D * 200) / 1e9)])
    const prof = e('IFCARBITRARYPROFILEDEFWITHVOIDS', '.AREA.', s('Floor with stair void'), polyline([[0, 0], [W, 0], [W, D], [0, D]]), list([polyline([[600, 3000], [1600, 3000], [1600, 6600], [600, 6600]])]))
    const s2 = styled(extrude(prof, 200, ax3(0, 0, -200)), ST.slab)
    const fl = e('IFCSLAB', guid(), '$', s('First floor slab'), '$', '$', place(st1Pl, 0, 0, 0), shape([s2]), '$', '.FLOOR.')
    contained[st1].push(fl)
    qto([fl], 'Qto_SlabBaseQuantities', [qLen('Depth', 200), qArea('NetArea', (W * D - 1000 * 3600) / 1e6)])
  }

  // ---- window type with a shared representation map → mapped items
  const winW = 1200, winH = 1400
  const yAxis = dir(0, -1, 0)
  const frame = styled(e('IFCEXTRUDEDAREASOLID', e('IFCRECTANGLEHOLLOWPROFILEDEF', '.AREA.', '$', ax2(winW / 2, winH / 2), f(winW), f(winH), f(70), '$', '$'), ax3(0, 150, 0, yAxis, X), Z, f(300)), ST.frame)
  const glass = styled(e('IFCEXTRUDEDAREASOLID', rectProf(winW - 140, winH - 140, winW / 2, winH / 2), ax3(0, 10, 0, yAxis, X), Z, f(20)), ST.glass)
  const winMap = e('IFCREPRESENTATIONMAP', ax3(), e('IFCSHAPEREPRESENTATION', body, s('Body'), s('SweptSolid'), list([frame, glass])))
  const winPset = e('IFCPROPERTYSET', guid(), '$', s('Pset_WindowCommon'), '$', list([single('ThermalTransmittance', 'IFCTHERMALTRANSMITTANCEMEASURE(1.1)'), single('GlazingAreaFraction', 'IFCPOSITIVERATIOMEASURE(0.72)'), single('IsExternal', 'IFCBOOLEAN(.T.)')]))
  const winType = e('IFCWINDOWTYPE', guid(), '$', s('W1 casement 1200×1400'), '$', '$', list([winPset]), list([winMap]), '$', '$', '.WINDOW.', '.SINGLE_PANEL.', '.F.', '$')
  const identity = e('IFCCARTESIANTRANSFORMATIONOPERATOR3D', '$', '$', pt(0, 0, 0), f(1), '$')
  const windows: string[] = []
  let wn = 1
  const opening = (hostPl: string, hostWall: string, filler: string, x: number, z: number, w: number, h: number) => {
    const sol = extrude(rectProf(w, h, w / 2, h / 2), 400, ax3(0, 200, 0, yAxis, X))
    const op = e('IFCOPENINGELEMENT', guid(), '$', s('Opening'), '$', '$', place(hostPl, x, 0, z), shape([sol]), '$', '.OPENING.')
    e('IFCRELVOIDSELEMENT', guid(), '$', '$', '$', hostWall, op)
    e('IFCRELFILLSELEMENT', guid(), '$', '$', '$', op, filler)
  }
  const win = (storey: string, host: { w: string; pl: string }, x: number) => {
    const item = e('IFCMAPPEDITEM', winMap, identity)
    const w = e('IFCWINDOW', guid(), '$', s(`Window W${String(wn).padStart(2, '0')}`), '$', '$', place(host.pl, x, 0, 900), e('IFCPRODUCTDEFINITIONSHAPE', '$', '$', list([e('IFCSHAPEREPRESENTATION', body, s('Body'), s('MappedRepresentation'), list([item]))])), s(`W${wn++}`), f(winH), f(winW), '.WINDOW.', '.SINGLE_PANEL.', '$')
    contained[storey].push(w)
    windows.push(w)
    opening(host.pl, host.w, w, x, 900, winW, winH)
  }
  ;[1000, 7600].forEach((x) => win(st0, g.S, x))
  ;[1200, 4400, 7600].forEach((x) => win(st1, u.S, x))
  ;[2000, 6500].forEach((x) => { win(st0, g.N, x); win(st1, u.N, x) })
  ;[3000].forEach((x) => { win(st0, g.Wt, x); win(st1, u.Wt, x); win(st0, g.E, x); win(st1, u.E, x) })
  e('IFCRELDEFINESBYTYPE', guid(), '$', '$', '$', list(windows), winType)

  // ---- front door
  {
    const leaf = styled(e('IFCEXTRUDEDAREASOLID', rectProf(1000, 2100, 500, 1050), ax3(0, 40, 0, yAxis, X), Z, f(80)), ST.door)
    const d = e('IFCDOOR', guid(), '$', s('Front door'), '$', '$', place(g.S.pl, 4500, 0, 0), shape([leaf]), s('D1'), f(2100), f(1000), '.DOOR.', '.SINGLE_SWING_LEFT.', '$')
    contained[st0].push(d)
    pset([d], 'Pset_DoorCommon', [single('IsExternal', 'IFCBOOLEAN(.T.)'), single('FireRating', "IFCLABEL('EI 30')"), single('SecurityRating', "IFCLABEL('RC2')")])
    opening(g.S.pl, g.S.w, d, 4500, 0, 1000, 2100)
  }

  // ---- porch: two round columns, an I-beam and a canopy slab
  for (const x of [3200, 6800]) {
    const c = e('IFCCOLUMN', guid(), '$', s(`Porch column ${x < 5000 ? 'west' : 'east'}`), '$', '$', place(st0Pl, x, -1500, 0), shape([styled(extrude(e('IFCCIRCLEPROFILEDEF', '.AREA.', '$', ax2(), f(120)), H), ST.frame)]), '$', '.COLUMN.')
    contained[st0].push(c)
    qto([c], 'Qto_ColumnBaseQuantities', [qLen('Length', H)])
  }
  {
    const ip = e('IFCISHAPEPROFILEDEF', '.AREA.', s('IPE 200'), ax2(), f(100), f(200), f(5.6), f(8.5), '$', '$', '$')
    const beam = e('IFCBEAM', guid(), '$', s('Porch beam IPE 200'), '$', '$', place(st0Pl, 3000, -1500, H - 100), shape([styled(extrude(ip, 4000, ax3(0, 0, 0, X, Yd)), ST.steel)]), '$', '.BEAM.')
    contained[st0].push(beam)
    pset([beam], 'Pset_BeamCommon', [single('Span', 'IFCPOSITIVELENGTHMEASURE(4000.)'), single('LoadBearing', 'IFCBOOLEAN(.T.)')])
    const can = e('IFCSLAB', guid(), '$', s('Porch canopy'), '$', '$', place(st0Pl, 0, 0, H), shape([styled(extrude(rectProf(4400, 1900, 5000, -1050), 150), ST.slab)]), '$', '.ROOF.')
    contained[st0].push(can)
  }

  // ---- stair: sawtooth prism as an IfcPolygonalFaceSet (IFC4)
  {
    const prof: [number, number][] = [[0, 0]]
    for (let k = 0; k < 15; k++) prof.push([k * 240, (k + 1) * 200], [(k + 1) * 240, (k + 1) * 200])
    prof.pop()
    prof.push([3360, 2760], [330, 0])
    const m = prof.length
    const coords = [...prof.map(([y, z]) => [0, y, z]), ...prof.map(([y, z]) => [1000, y, z])]
    const faces = [
      e('IFCINDEXEDPOLYGONALFACE', list(prof.map((_, i) => i + 1))),
      e('IFCINDEXEDPOLYGONALFACE', list(prof.map((_, i) => 2 * m - i))),
      ...prof.map((_, i) => e('IFCINDEXEDPOLYGONALFACE', list([i + 1, m + i + 1, m + ((i + 1) % m) + 1, ((i + 1) % m) + 1]))),
    ]
    const fs = styled(e('IFCPOLYGONALFACESET', e('IFCCARTESIANPOINTLIST3D', list(coords.map((c) => list(c.map(f))))), '.T.', list(faces), '$'), ST.wood)
    const st = e('IFCSTAIR', guid(), '$', s('Main stair'), '$', '$', place(st0Pl, 600, 3060, 0), shape([fs], 'Tessellation'), '$', '.STRAIGHT_RUN_STAIR.')
    contained[st0].push(st)
    pset([st], 'Pset_StairCommon', [single('NumberOfRiser', 'IFCCOUNTMEASURE(15)'), single('RiserHeight', 'IFCPOSITIVELENGTHMEASURE(200.)'), single('TreadLength', 'IFCPOSITIVELENGTHMEASURE(240.)')])
  }

  // ---- gable walls as faceted B-reps (triangular prisms)
  for (const [name, x0] of [['1F west gable', 0], ['1F east gable', W - T]] as [string, number][]) {
    const P = (x: number, y: number, z: number) => pt(x, y, z)
    const a = [P(x0, 0, H), P(x0, D, H), P(x0, D / 2, H + 1950)]
    const b = [P(x0 + T, 0, H), P(x0 + T, D, H), P(x0 + T, D / 2, H + 1950)]
    const face = (pts: string[]) => e('IFCFACE', list([e('IFCFACEOUTERBOUND', e('IFCPOLYLOOP', list(pts)), '.T.')]))
    const shell = e('IFCCLOSEDSHELL', list([face([a[0], a[2], a[1]]), face(b), face([a[0], a[1], b[1], b[0]]), face([a[1], a[2], b[2], b[1]]), face([a[2], a[0], b[0], b[2]])]))
    const w = e('IFCWALL', guid(), '$', s(name), '$', s('Gable wall'), place(st1Pl, 0, 0, 0), shape([styled(e('IFCFACETEDBREP', shell), ST.wall)], 'Brep'), '$', '.STANDARD.')
    contained[st1].push(w)
    pset([w], 'Pset_WallCommon', [single('IsExternal', 'IFCBOOLEAN(.T.)'), single('LoadBearing', 'IFCBOOLEAN(.F.)')])
  }

  // ---- roof: thick gable as an IfcTriangulatedFaceSet (IFC4)
  {
    const o = 400, t = 200, rz = 2000
    const top = [[-o, -o, 0], [W + o, -o, 0], [-o, D / 2, rz], [W + o, D / 2, rz], [-o, D + o, 0], [W + o, D + o, 0]]
    const coords = [...top, ...top.map(([x, y, z]) => [x, y, z - t])]
    const quad = (a: number, b: number, c: number, d: number) => [[a, b, c], [a, c, d]]
    const tris = [
      ...quad(1, 2, 4, 3), ...quad(3, 4, 6, 5), ...quad(7, 9, 10, 8), ...quad(9, 11, 12, 10),
      ...quad(1, 7, 8, 2), ...quad(5, 6, 12, 11), ...quad(1, 3, 9, 7), ...quad(3, 5, 11, 9), ...quad(2, 8, 10, 4), ...quad(4, 10, 12, 6),
    ]
    const fs = styled(e('IFCTRIANGULATEDFACESET', e('IFCCARTESIANPOINTLIST3D', list(coords.map((c) => list(c.map(f))))), '$', '.T.', list(tris.map((tr) => list(tr))), '$'), ST.roof)
    const roof = e('IFCROOF', guid(), '$', s('Gable roof'), '$', '$', place(st1Pl, 0, 0, H + 160), shape([fs], 'Tessellation'), '$', '.GABLE_ROOF.')
    contained[st1].push(roof)
    pset([roof], 'Pset_RoofCommon', [single('IsExternal', 'IFCBOOLEAN(.T.)'), single('ProjectedArea', 'IFCAREAMEASURE(98.6)')])
    // chimney: hollow rectangle extrusion through the roof
    const ch = e('IFCCHIMNEY', guid(), '$', s('Chimney'), '$', '$', place(st1Pl, 7800, 5600, 0), shape([styled(extrude(e('IFCRECTANGLEHOLLOWPROFILEDEF', '.AREA.', '$', ax2(), f(600), f(600), f(110), '$', '$'), 5000), ST.brick)]), '$', '.NOTDEFINED.')
    contained[st1].push(ch)
  }

  // ---- spaces
  const space = (storey: string, stPl: string, name: string, x0: number, y0: number, x1: number, y1: number, use: string) => {
    const sp = e('IFCSPACE', guid(), '$', s(name), '$', '$', place(stPl, 0, 0, 0), shape([styled(extrude(rectProf(x1 - x0, y1 - y0, (x0 + x1) / 2, (y0 + y1) / 2), 2600), ST.space)]), s(name), '.ELEMENT.', '.INTERNAL.', '$')
    e('IFCRELAGGREGATES', guid(), '$', '$', '$', storey, list([sp]))
    pset([sp], 'Pset_SpaceCommon', [single('Reference', `IFCIDENTIFIER('${use}')`), single('IsExternal', 'IFCBOOLEAN(.F.)'), single('HandicapAccessible', 'IFCBOOLEAN(.T.)')])
    qto([sp], 'Qto_SpaceBaseQuantities', [qArea('NetFloorArea', Number((((x1 - x0) * (y1 - y0)) / 1e6).toFixed(2))), qLen('Height', 2600)])
  }
  space(st0, st0Pl, 'Living room', T, T, 5000, D - T, 'LIV')
  space(st0, st0Pl, 'Kitchen', 5120, 4620, W - T, D - T, 'KIT')
  space(st0, st0Pl, 'Hall', 5120, T, W - T, 4500, 'HAL')
  space(st1, st1Pl, 'Bedroom 1', T, T, 5000, D - T, 'BED')
  space(st1, st1Pl, 'Bedroom 2', 5000, T, W - T, D - T, 'BED')

  // ---- washbasin with a revolved solid (not supported by the viewer on purpose)
  {
    const prof = rectProf(250, 150, 125, 75)
    const rev = e('IFCREVOLVEDAREASOLID', prof, ax3(), e('IFCAXIS1PLACEMENT', pt(0, 0, 0), Yd), f(6.283185))
    const sink = e('IFCSANITARYTERMINAL', guid(), '$', s('Washbasin'), '$', '$', place(st1Pl, 9300, 7400, 850), shape([styled(rev, ST.porcelain)]), '$', '.WASHHANDBASIN.')
    contained[st1].push(sink)
  }

  for (const [storey, els] of Object.entries(contained)) e('IFCRELCONTAINEDINSPATIALSTRUCTURE', guid(), '$', s('Storey contents'), '$', list(els), storey)

  return [
    'ISO-10303-21;',
    'HEADER;',
    "FILE_DESCRIPTION(('ViewDefinition [ReferenceView]'),'2;1');",
    "FILE_NAME('sample-house.ifc','2026-10-18T12:00:00',('Browser Toolbox'),('The Browser Toolbox authors'),'','Browser Toolbox BIM sample generator','');",
    "FILE_SCHEMA(('IFC4'));",
    'ENDSEC;',
    'DATA;',
    ...L,
    'ENDSEC;',
    'END-ISO-10303-21;',
    '',
  ].join('\n')
}
