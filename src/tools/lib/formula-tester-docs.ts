export function sampleCells(): Record<string, string> {
  const cells: Record<string, string> = {}
  const L = 'ABCDEFGHIJ'
  ROWS.forEach((row, r) => row.forEach((v, c) => (cells[`${L[c]}${r + 1}`] = String(v))))
  for (let r = 2; r <= 9; r++) cells[`G${r}`] = `=D${r}*E${r}`
  SUMMARY.forEach(([a, b], i) => { cells[`I${i + 1}`] = a; cells[`J${i + 1}`] = b })
  return cells
}
